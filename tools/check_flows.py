"""Check N2 connection initiators and render the single-VM Docker probe topology.

The probe topology is intentionally separate from production application containers.
It publishes no ports and cannot authorize an operational TC or external ICD flow.
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
N2_PATH = ROOT / "interfaces" / "n2_chart.json"
ROLES = ("portal", "ros", "mps", "fds", "dgs-archive", "dgs-gs", "dgs-net")
EXTERNAL = ("sdc", "space-track")
DMZ = {"dgs-gs", "dgs-net"}
OPERATIONS = {"portal", "ros", "mps", "fds", "dgs-archive"}
PROBE_IMAGE = "pado-stage2-test:local"
TRANSPORT_PORTS = {"HTTPS": 443, "SFTP_PUSH": 2222,
                   "SFTP_PULL": 2222, "TLS_STREAM": 7001}


def approved_connections(n2_path: Path = N2_PATH) -> list[dict]:
    chart = json.loads(n2_path.read_text(encoding="utf-8"))
    if chart["rules"]["unlisted_flow"] != "deny":
        raise ValueError("N2 must default to deny")
    ids: set[str] = set()
    connections = []
    for edge in chart["approved_flows"]:
        edge_id = edge["id"]
        if edge_id in ids:
            raise ValueError(f"duplicate N2 ID: {edge_id}")
        ids.add(edge_id)
        source = edge["connection_from"]
        destination = edge["connection_to"]
        port = edge["port"]
        if edge["transport"] == "TBD(ICD)":
            if source is not None or destination is not None or port is not None:
                raise ValueError(f"TBD flow opened: {edge_id}")
            continue
        if not source or not destination or type(port) is not int or not 1 <= port <= 65535:
            raise ValueError(f"incomplete flow: {edge_id}")
        if source not in ROLES + EXTERNAL or destination not in ROLES + EXTERNAL:
            raise ValueError(f"unknown endpoint: {edge_id}")
        if TRANSPORT_PORTS.get(edge["transport"]) != port:
            raise ValueError(f"unexpected transport or port: {edge_id}")
        if source in DMZ and destination in OPERATIONS:
            raise ValueError(f"DMZ initiated connection: {edge_id}")
        if source == "sdc" and destination != "dgs-archive":
            raise ValueError(f"SDC reaches another subsystem: {edge_id}")
        connections.append({"id": edge_id, "reference": edge["reference"],
                            "source": source, "destination": destination,
                            "port": port, "transport": edge["transport"]})
    if ids != {f"N{i:02d}" for i in range(1, 22)}:
        raise ValueError("N2 ID set changed; review new edges before deployment")
    return connections


def probe_pairs(connections: list[dict]) -> list[tuple[str, str]]:
    pairs = {tuple(sorted((edge["source"], edge["destination"])))
             for edge in connections
             if edge["source"] in ROLES and edge["destination"] in ROLES}
    # The portal API pair is reserved for stage 9; no API is deployed here.
    pairs.update({("portal", "ros"), ("mps", "portal")})
    return sorted(pairs)


def network_name(pair: tuple[str, str]) -> str:
    return "pair_" + pair[0].replace("-", "_") + "__" + pair[1].replace("-", "_")


def compose_text(pairs: list[tuple[str, str]]) -> str:
    lines = [
        "# Generated by tools/check_flows.py. Disposable connectivity probes only.",
        "services:",
    ]
    for role in ROLES:
        member = [network_name(pair) for pair in pairs if role in pair]
        lines += [
            f"  probe-{role}:",
            f"    image: {PROBE_IMAGE}",
            "    command: [\"sh\", \"-c\", \"echo pado-stage7-probe-start; exec sleep infinity\"]",
            "    read_only: true",
            "    cap_drop: [ALL]",
            "    security_opt: [\"no-new-privileges:true\"]",
            "    tmpfs: [\"/tmp\"]",
            "    logging:",
            "      driver: journald",
            "    networks:",
        ]
        lines += [f"      - {name}" for name in member]
    lines.append("networks:")
    for pair in pairs:
        lines += [f"  {network_name(pair)}:", "    driver: bridge", "    internal: true"]
    return "\n".join(lines) + "\n"


def plan(connections: list[dict]) -> dict:
    pairs = probe_pairs(connections)
    return {
        "version": 1,
        "scope": "single-linux-vm-disposable-docker-probes",
        "n2_connections": connections,
        "probe_networks": [{"name": network_name(pair), "members": list(pair)}
                           for pair in pairs],
        "publications": [],
        "limitations": [
            "A shared bridge permits both peers to initiate connections; direction requires service and peer policy.",
            "The Docker host and privileged containers can reach or alter bridge networks.",
            "No external ICD, SDC, registry or portal service is deployed by this probe.",
        ],
    }


def render(output: Path, n2_path: Path = N2_PATH) -> None:
    connections = approved_connections(n2_path)
    pairs = probe_pairs(connections)
    output.mkdir(parents=True, exist_ok=True)
    (output / "compose.probe.yaml").write_text(compose_text(pairs), encoding="utf-8",
                                                newline="\n")
    (output / "flow-plan.json").write_text(
        json.dumps(plan(connections), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8", newline="\n")


def check(output: Path, n2_path: Path = N2_PATH) -> None:
    with tempfile.TemporaryDirectory() as temp:
        expected = Path(temp)
        render(expected, n2_path)
        for name in ("compose.probe.yaml", "flow-plan.json"):
            if (output / name).read_bytes() != (expected / name).read_bytes():
                raise ValueError(f"out-of-date or unexpected topology: {name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("render", "check"))
    parser.add_argument("--output", type=Path, default=ROOT / "deploy" / "stage7")
    args = parser.parse_args()
    if args.command == "render":
        render(args.output)
    else:
        check(args.output)
    connections = approved_connections()
    print(f"{args.command}: {len(connections)} resolved N2 entries, "
          f"{len(probe_pairs(connections))} private Docker pairs, zero published ports")


if __name__ == "__main__":
    main()
